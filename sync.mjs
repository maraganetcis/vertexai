import assert from 'node:assert/strict';
import {mergeDaymateStates,createCloudSync} from '../sync.js';
const template=()=>({version:1,demo:false,profile:{name:'나'},tasks:[],events:[],notes:[],lessons:[{day:1,subjects:[]}],studySessions:[],chat:[],settings:{}});
const local=template(),remote=template();
local.tasks=[{id:'t1',text:'로컬 변경',done:false},{id:'t2',text:'로컬 과제'}];
remote.tasks=[{id:'t1',text:'클라우드 변경',done:true},{id:'t3',text:'클라우드 과제'}];
local.notes=[{id:'n1',title:'로컬 노트'}]; remote.notes=[{id:'n2',title:'클라우드 노트'}];
local.lessons=[{day:1,subjects:[{id:'l1',title:'국어'}]}];
remote.lessons=[{day:1,subjects:[{id:'l2',title:'수학'}]}];
const merged=mergeDaymateStates(local,remote);
assert.equal(merged.tasks.length,4,'충돌하는 ID의 양쪽 과제를 보존해야 함');
assert.ok(merged.tasks.some(x=>x.text==='로컬 변경'));
assert.ok(merged.tasks.some(x=>x.text==='클라우드 변경'));
assert.equal(merged.notes.length,2);
assert.equal(merged.lessons[0].subjects.length,2);
assert.equal(mergeDaymateStates({...local,demo:true},remote),remote,'신규 기기는 클라우드 자료 우선');
assert.equal(mergeDaymateStates(local,{...remote,demo:true}),local,'클라우드가 예시만 있으면 로컬 우선');
const sync=createCloudSync({getState:()=>local,replaceState:()=>{},status:()=>{},toast:()=>{}});
assert.equal(sync.configured,false,'설정 이전에는 Google 동기화를 비활성화해야 함');
assert.equal(sync.connected,false);
console.log('PASS: 로컬/클라우드 충돌 자료 보존, 예시 데이터 우선순위, 미설정 상태 동기화 차단');
