import assert from 'node:assert/strict';
import {readFile, readdir} from 'node:fs/promises';
const files=['index.html','manifest.webmanifest','app.js','sync.js','firebase-config.js','netlify.toml','README.md','SECURITY.md','VOICE_SETUP.md'];
const map=Object.fromEntries(await Promise.all(files.map(async f=>[f,await readFile(f,'utf8')])));
assert.match(map['index.html'],/Vertex/);
assert.match(map['index.html'],/Synox Studios/);
assert.match(map['manifest.webmanifest'],/Vertex/);
assert.match(map['app.js'],/voiceDictate/);
assert.match(map['app.js'],/voiceRead/);
assert.match(map['app.js'],/x.title!==\'DAYMATE 사용법\'/);
assert.match(map['app.js'],/daymate-ai-personal-v1/, 'legacy local state key must stay unchanged');
assert.match(map['sync.js'],/daymate-safety-/, 'legacy safety snapshots must stay unchanged');
assert.match(map['sync.js'],/VERTEX_FIREBASE_CONFIG/);
assert.match(map['firebase-config.js'],/VERTEX_FIREBASE_CONFIG = null/);
assert.match(map['netlify.toml'],/vertex-voice/);
assert.match(await readFile('sw.js','utf8'),/\^\(\?:daymate-shell-\|vertex-shell-\)/);
assert.match(map['README.md'],/Synox Studios/);
assert.deepEqual((await readdir('netlify/functions')).sort(),['lib','vertex-voice.mjs']);
assert.doesNotMatch(map['README.md'],/BEGIN PRIVATE KEY|dmv1_[0-9a-f]{24}_[A-Za-z0-9_-]{43}/);
assert.equal((await readdir('public')).some(f=>f.endsWith('.json')&&f!=='manifest.webmanifest'),false);
console.log('PASS: Vertex brand, legacy data/backup compatibility, server-only code and no deployed secrets');
